#!/bin/sh
# Prepares already-mounted filesystems for Multisuite on a Linux server:
# creates <mount>/multisuite with its identity marker and 0700 private directory,
# then writes compose.nas.yaml (local, ignored by Git) with the bind mounts and
# NAS_* settings. Never formats, partitions or mounts anything.
# Usage: make nas-apply TARGETS="/srv/disk1 /srv/disk2" [UPLOAD=disk1] [YES=1]
set -eu
cd "$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
FINDMNT=${FINDMNT:-findmnt}
TARGETS=${TARGETS:-}
YES=${YES:-0}
die() { echo "nas-apply: $*" >&2; exit 1; }
# Stable volume ID from the mount point name: lowercase [a-z0-9-], never starting with a digit.
target_id() {
    id=$(basename "$1" | tr 'A-Z_.' 'a-z--' | tr -cd 'a-z0-9-' | cut -c1-40)
    case "$id" in ''|[0-9-]*) id="disk-$id" ;; esac
    printf '%s' "$id"
}
[ "$(uname -s)" = Linux ] || die "needs a Linux host; with Docker Desktop use the dev NAS (make up)."
[ -n "$TARGETS" ] || die 'indica TARGETS="/punto/de/montaje ..." (ver make nas-discover).'
uid=$(sed -n 's/^DEV_UID="\{0,1\}\([0-9][0-9]*\)"\{0,1\}$/\1/p' .env 2>/dev/null | tail -1)
gid=$(sed -n 's/^DEV_GID="\{0,1\}\([0-9][0-9]*\)"\{0,1\}$/\1/p' .env 2>/dev/null | tail -1)
uid=${uid:-1000}; gid=${gid:-1000}

ids=''; json=''; mounts=''; plan=''
for target in $TARGETS; do
    case "$target" in /*) ;; *) die "$target: usa rutas absolutas." ;; esac
    case "$target" in /|/boot|/boot/*|/efi|/usr|/var|/proc*|/sys*|/dev*|/run*) die "$target: es del sistema, no se usa." ;; esac
    case "$target" in *[!A-Za-z0-9/._-]*) die "$target: solo letras, números, / . _ -" ;; esac
    info=$("$FINDMNT" -rn -M "$target" -o SOURCE,FSTYPE,UUID,OPTIONS 2>/dev/null || true)
    [ -n "$info" ] || die "$target no es un punto de montaje (monta el disco antes; este script no monta nada)."
    set -- $info
    fstype=$2; fsuuid=${3:-}; options=${4:-}
    case ",$options," in *,ro,*) die "$target está montado en solo lectura." ;; esac
    id=$(target_id "$target")
    case " $ids " in *" $id "*) die "dos destinos generan el mismo identificador '$id'; renombra un punto de montaje." ;; esac
    group=$(printf 'fs-%s' "$(printf '%s' "${fsuuid:-$id}" | tr 'A-Z' 'a-z' | tr -cd 'a-z0-9' | cut -c1-12)")
    root="$target/multisuite"
    if [ -f "$root/.multisuite-volume-id" ] && [ "$(cat "$root/.multisuite-volume-id")" != "$id" ]; then
        die "$root ya tiene otra marca ($(cat "$root/.multisuite-volume-id")); no se sobrescribe."
    fi
    ids="$ids $id"
    plan="$plan\n  $target ($fstype) -> /nas/$id  [id=$id, grupo=$group]"
    json="$json${json:+,}{\"id\":\"$id\",\"group\":\"$group\",\"path\":\"/nas/$id\",\"reserve_bytes\":10737418240}"
    mounts="$mounts\n    - \"$root:/nas/$id\""
done
upload=${UPLOAD:-$(echo $ids | cut -d' ' -f1)}
case " $ids " in *" $upload "*) ;; *) die "UPLOAD=$upload no está entre los destinos ($ids)." ;; esac

printf 'Se va a preparar:%b\nArchivos privados en: %s\nPropietario de las carpetas: %s:%s\n' "$plan" "$upload" "$uid" "$gid"
if [ "$YES" != 1 ]; then
    printf '¿Continuar? [s/N] '
    read -r answer
    case "$answer" in s|S|si|SI|sí|y|Y) ;; *) die "cancelado." ;; esac
fi

for target in $TARGETS; do
    id=$(target_id "$target")
    root="$target/multisuite"
    mkdir -p "$root/.multisuite-private" || die "no se puede escribir en $target (¿ejecutar con sudo?)."
    [ -f "$root/.multisuite-volume-id" ] || printf '%s\n' "$id" > "$root/.multisuite-volume-id"
    chown "$uid:$gid" "$root" "$root/.multisuite-volume-id" "$root/.multisuite-private" || die "chown falló en $root (¿sudo?)."
    chmod 0755 "$root"; chmod 0644 "$root/.multisuite-volume-id"; chmod 0700 "$root/.multisuite-private"
done

tmp=$(mktemp ./.compose-nas.XXXXXX)
{
    printf '# Generated by make nas-apply on %s. Local to this server; ignored by Git.\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '# Re-run make nas-apply to change it. Replaces the dev NAS overlay automatically.\n'
    printf 'x-nas: &nas\n  volumes:%b\n' "$mounts"
    printf '    - "./local/nas-hardware.json:/opt/multisuite/nas-hardware.json:ro"\n'
    printf '  environment:\n'
    printf "    NAS_STORAGE_VOLUMES: '[%s]'\n" "$json"
    printf '    NAS_UPLOADS_ENABLED: "true"\n    NAS_UPLOAD_LOCATION: "%s"\n' "$upload"
    printf '    NAS_HARDWARE_SNAPSHOT: "/opt/multisuite/nas-hardware.json"\n'
    printf 'services:\n  app: *nas\n  worker: *nas\n  scheduler: *nas\n'
} > "$tmp"
mv "$tmp" compose.nas.yaml
mkdir -p local
printf '%s\n' $TARGETS > local/nas-targets
sh scripts/nas-discover.sh >/dev/null 2>&1 || true
[ -f local/nas-hardware.json ] || printf '{}\n' > local/nas-hardware.json
echo "Listo: compose.nas.yaml creado. Ejecuta make up; los límites se fijan solos y puedes ajustarlos en Almacenamiento."
